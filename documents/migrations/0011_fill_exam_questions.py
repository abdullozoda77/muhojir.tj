    if ExamQuestion.objects.exists():
        return
    for section, rows in (("language", LANGUAGE), ("history", HISTORY), ("law", LAW)):
        for order, row in enumerate(rows, start=1):
            question, options, answer, explanation, *listen = row
            ExamQuestion.objects.create(
                section=section, order=order, question=question, options=options, answer=answer,
                explanation=explanation, listen_text=listen[0] if listen else "",
            )


